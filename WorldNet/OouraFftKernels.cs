            double wkr = 0.5 - c[nc - kk];
            double wki = c[kk];
            double xr = a[j] - a[k];
            double xi = a[j + 1] + a[k + 1];
            double yr = wkr * xr - wki * xi;
            double yi = wkr * xi + wki * xr;
            a[j] -= yr;
            a[j + 1] -= yi;
            a[k] += yr;
            a[k + 1] -= yi;
        }
    }

    private static void RftBSub(int n, double* a, int nc, double* c)
    {
        int m = n >> 1;
        int ks = 2 * nc / m;
        int kk = 0;
        for (int j = 2; j < m; j += 2)
        {
            int k = n - j;
            kk += ks;
            double wkr = 0.5 - c[nc - kk];
            double wki = c[kk];
            double xr = a[j] - a[k];
            double xi = a[j + 1] + a[k + 1];
            double yr = wkr * xr + wki * xi;
            double yi = wkr * xi - wki * xr;
            a[j] -= yr;
            a[j + 1] -= yi;
            a[k] += yr;
            a[k + 1] -= yi;
        }
    }
